export function resolveCampaignEnding(state) {
  const { intimacy, safety, flags } = state;
  const will = flags.includes("will_to_stay") || flags.includes("home_named");
  const tease = flags.includes("mid_tease");
  const care =
    flags.includes("her_care_start") ||
    flags.includes("her_care_active") ||
    flags.includes("hairdryer") ||
    flags.includes("sticky_note");
  const home =
    flags.includes("roommate_deal") ||
    flags.includes("blanket_cook") ||
    flags.includes("gave_bed");

  if (safety < 30) {
    return {
      title: "灯关得很轻",
      text: "过夜袋被带走了。门合上时几乎没有声音。\n第一幕里，家还没来得及成为她愿意回来的理由。\n中后期仍预留着——若再开始，也许节奏可以更慢一点。",
    };
  }

  if (intimacy >= 55 && safety >= 45 && will && tease && care) {
    return {
      title: "第一幕 · 灯还亮着",
      text: "她肯把这里称作回去的地方：吹干的头发、盖过的毯子、内袋里的便利贴、手里的备用钥匙。\n活下去的意愿稳住了；心动已经发生，却还不好意思命名。\n\n【中期预留】她将发现你并不总是轻松，并试着主动走近。\n【后期预留】彼此依赖，共同生活，朝更长的约定走去。",
    };
  }

  if (intimacy >= 40 && home) {
    return {
      title: "坐标有效",
      text: "第一幕落下。室友条款、热饭、亲昵与边界——生活已先于告白到位。\n恋爱的线路埋着，却还不急着张扬。\n\n中期与后期仍空着：反向靠近，再是互相依赖。",
    };
  }

  return {
    title: "第一幕 · 未写完的备注",
    text: "你们交换过热饮、沉默与几次靠得很近的照顾。意愿还在摇晃。\n灯可以再留。中后期的章节位，已经空在前面。",
  };
}

    return {
      title: "第一幕 · 灯还亮着",
      text: "她肯把这里称作回去的地方：吹干的头发、盖过的毯子、内袋里的便利贴、手里的备用钥匙。\n活下去的意愿稳住了；心动已经发生，却还不好意思命名。\n\n【中期预留】她将发现你并不总是轻松，并试着主动走近。\n【后期预留】彼此依赖，共同生活，朝更长的约定走去。",
    };
